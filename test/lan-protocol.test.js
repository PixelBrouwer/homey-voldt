'use strict';

const { test } = require('node:test');
const assert = require('node:assert/strict');
const net = require('node:net');
const { createHmac } = require('node:crypto');
const { once } = require('node:events');
const { TuyaLanClient } = require('../lib/tuya-lan-client');
const { encodePacket, decodePacket, readHeader, deriveSessionKey } = require('../lib/tuya-lan-codec');
const fixture = require('./fixtures/tuya-lan-vectors.json');

test('LAN encoding matches fixed frames generated by the unmodified upstream TuyAPI encoder', () => {
  for (const vector of fixture.vectors) {
    const actual = encodePacket({ version: vector.version, key: vector.key, sequence: vector.sequence,
      command: vector.command, payload: vector.data,
      ...(vector.version === '3.5' ? { iv: Buffer.from('170000000012') } : {}) });
    assert.equal(actual.toString('hex'), vector.hex, `version ${vector.version}`);
    const decoded = decodePacket(Buffer.from(vector.hex, 'hex'), { version: vector.version, key: vector.key, expectReturnCode: false });
    assert.deepEqual(JSON.parse(decoded.payload.toString()), vector.data);
  }
});

test('LAN session keys match fixed derivations generated by the upstream cipher', () => {
  for (const vector of fixture.sessionVectors) {
    const result = deriveSessionKey(vector.key, Buffer.from(vector.localNonce, 'hex'), Buffer.from(vector.remoteNonce, 'hex'), vector.version);
    assert.equal(result.toString('hex'), vector.sessionKey);
  }
});

test('LAN decoding rejects changed GCM tags, ciphertext and declared packet lengths', () => {
  const vector = fixture.vectors.find(item => item.version === '3.5');
  const packet = Buffer.from(vector.hex, 'hex');
  for (const index of [20, 35, packet.length - 5]) {
    const corrupt = Buffer.from(packet);
    corrupt[index] ^= 1;
    assert.throws(() => decodePacket(corrupt, { version: '3.5', key: vector.key, expectReturnCode: false }), /authenticatie/);
  }
  const oversized = Buffer.from(packet);
  oversized.writeUInt32BE(0xffffffff, 14);
  assert.throws(() => readHeader(oversized), /pakketlengte/);
});

async function cableServer(t, version, { dropWriteReply = false, badHandshake = false, invalidTag = false } = {}) {
  const key = Buffer.from('0123456789abcdef');
  const state = { value: false, writes: 0, handshakes: 0, queries: 0, openSockets: new Set(), errors: [] };
  const server = net.createServer(socket => {
    state.openSockets.add(socket);
    socket.on('error', error => state.errors.push(error));
    socket.on('close', () => state.openSockets.delete(socket));
    let pending = Buffer.alloc(0);
    let sessionKey = key;
    let clientNonce;
    const remoteNonce = Buffer.from('abcdef0123456789');
    const respond = (command, payload, sequence = 54321) => encodePacket({ version, key: sessionKey, sequence, command, payload, returnCode: 0 });
    socket.on('data', chunk => {
      try {
        pending = Buffer.concat([pending, chunk]);
        while (true) {
          const header = readHeader(pending);
          if (!header || pending.length < header.totalLength) return;
          const packet = decodePacket(pending.subarray(0, header.totalLength), { version, key: sessionKey, expectReturnCode: false });
          pending = pending.subarray(header.totalLength);
          if (packet.command === 3) {
            clientNonce = packet.payload;
            assert.equal(clientNonce.length, 16);
            state.handshakes++;
            const signed = createHmac('sha256', key).update(clientNonce).digest();
            if (badHandshake) signed[0] ^= 1;
            const response = respond(4, Buffer.concat([remoteNonce, signed]));
            socket.write(response.subarray(0, 7));
            setImmediate(() => socket.write(response.subarray(7)));
          } else if (packet.command === 5) {
            assert.deepEqual(packet.payload, createHmac('sha256', key).update(remoteNonce).digest());
            sessionKey = deriveSessionKey(key, clientNonce, remoteNonce, version);
          } else if (packet.command === (version === '3.3' ? 10 : 16)) {
            state.queries++;
            const request = JSON.parse(packet.payload.toString());
            if (version === '3.3') assert.equal(request.devId, 'test-device');
            else assert.deepEqual(request, {});
            // Unrelated response sequence and an empty ack before the actual DPS report.
            const ack = respond(packet.command, Buffer.alloc(0));
            const report = respond(8, version === '3.3' ? { dps: { '101': state.value } } : { protocol: 4, data: { dps: { '101': state.value } } });
            if (invalidTag) report[report.length - 5] ^= 1;
            socket.write(Buffer.concat([ack, report]));
          } else if (packet.command === (version === '3.3' ? 7 : 13)) {
            const request = JSON.parse(packet.payload.toString());
            const dps = version === '3.3' ? request.dps : request.data.dps;
            if (version !== '3.3') assert.equal(request.protocol, 5);
            state.writes++;
            state.value = dps['101'];
            if (!dropWriteReply) socket.write(respond(packet.command, Buffer.alloc(0)));
          } else throw new Error(`Unexpected command ${packet.command}`);
        }
      } catch (error) { state.errors.push(error); socket.destroy(); }
    });
  });
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(async () => {
    for (const socket of state.openSockets) socket.destroy();
    await new Promise(resolve => server.close(resolve));
  });
  return { state, client: () => new TuyaLanClient({ host: '127.0.0.1', deviceId: 'test-device', localKey: key,
    version, timeoutMs: 300, port: server.address().port }) };
}

for (const version of ['3.3', '3.4', '3.5']) {
  test(`LAN ${version}: reads status, writes one command, reads back and closes every socket`, async t => {
    const { state, client } = await cableServer(t, version);
    const first = await client().getStatus();
    assert.equal(first.dps['101'], false);
    assert.equal(state.writes, 0);
    assert.deepEqual(await client().setDps({ '101': true }), { acknowledged: true });
    assert.equal((await client().getStatus()).dps['101'], true);
    assert.equal(state.writes, 1);
    assert.equal(state.queries, 2);
    assert.equal(state.handshakes, version === '3.3' ? 0 : 3);
    const deadline = Date.now() + 1000;
    while (state.openSockets.size && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 5));
    assert.equal(state.openSockets.size, 0, 'client must release its TCP connection after every operation');
    assert.deepEqual(state.errors, []);
  });
}

test('LAN 3.5: an accepted write with a missing reply is reported uncertain and never repeated', async t => {
  const { state, client } = await cableServer(t, '3.5', { dropWriteReply: true });
  await assert.rejects(client().setDps({ '101': true }), error => {
    assert.equal(error.code, 'TUYA_LAN_UNCONFIRMED');
    assert.equal(error.commandSent, true);
    return true;
  });
  assert.equal(state.writes, 1);
  assert.equal(state.value, true);
});

test('LAN 3.5: a failed key challenge prevents status queries and writes', async t => {
  const { state, client } = await cableServer(t, '3.5', { badHandshake: true });
  await assert.rejects(client().setDps({ '101': true }), /sleutel/);
  assert.equal(state.queries, 0);
  assert.equal(state.writes, 0);
});

test('LAN 3.5: an invalid status authentication tag is rejected', async t => {
  const { state, client } = await cableServer(t, '3.5', { invalidTag: true });
  await assert.rejects(client().getStatus(), /authenticatie/);
  assert.equal(state.writes, 0);
});
